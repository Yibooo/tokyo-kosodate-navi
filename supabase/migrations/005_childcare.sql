-- =============================================
-- Phase B2: 保育施設情報テーブル
-- =============================================
-- データソース:
--   施設定員: こども家庭庁「保育所等関連状況取りまとめ」
--   待機児童: 東京都福祉局・こども家庭庁（各年4月1日時点）
--   出生数  : 東京都統計局「人口の動き」
-- =============================================

-- ① 施設数・定員テーブル
CREATE TABLE IF NOT EXISTS childcare_facilities (
  ward         VARCHAR(20)  NOT NULL,
  fiscal_year  SMALLINT     NOT NULL,
  category     VARCHAR(20)  NOT NULL,  -- '認可保育所' | '認定こども園' | '小規模保育等'
  count        SMALLINT     NOT NULL,  -- 施設数（推計値含む）
  capacity     INT          NOT NULL,  -- 定員数
  estimated    BOOLEAN      NOT NULL DEFAULT false,  -- true = 推計値
  PRIMARY KEY (ward, fiscal_year, category)
);

-- ② 待機児童数テーブル（合計）
CREATE TABLE IF NOT EXISTS waiting_children (
  ward                 VARCHAR(20) NOT NULL,
  fiscal_year          SMALLINT    NOT NULL,
  total_waiting        SMALLINT    NOT NULL DEFAULT 0,
  total_hidden_waiting SMALLINT,  -- 利用保留（NULL = データなし）
  PRIMARY KEY (ward, fiscal_year)
);

-- ③ 出生数トレンドテーブル
CREATE TABLE IF NOT EXISTS birth_trends (
  ward         VARCHAR(20) NOT NULL,
  fiscal_year  SMALLINT    NOT NULL,
  birth_count  INT         NOT NULL,
  PRIMARY KEY (ward, fiscal_year)
);

-- =============================================
-- インデックス
-- =============================================
CREATE INDEX IF NOT EXISTS idx_childcare_facilities_ward ON childcare_facilities(ward);
CREATE INDEX IF NOT EXISTS idx_waiting_children_ward     ON waiting_children(ward);
CREATE INDEX IF NOT EXISTS idx_birth_trends_ward         ON birth_trends(ward);

